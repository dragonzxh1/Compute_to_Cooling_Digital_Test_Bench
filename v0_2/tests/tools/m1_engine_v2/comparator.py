RULES = tuple(x['id'] for x in read('phase5_r5_2_1r4_7_c3_a_comparator_registration.json')['rules'])


def _native(core):
    return {k: decode(v) for k, v in core.items()}


def _evidence_vector(core):
    return tuple(core.get(name, {'type': 'absent'}) for name in (
        'carried_suspicion_evidence', 'credited_motion', 'confirmed_latched',
        'response_history', 'consumed_samples'))


def _old_qualification(before, pre):
    """Independent frozen-model predicates, not values generated by the split."""
    q = _native(before)
    m = pre['measurement']
    age = None if m['sample_ns'] is None else m['time_ns'] - m['sample_ns']
    valid = (m['quality'] == 'VALID' and m['measured_speed'] is not None
             and math.isfinite(m['measured_speed']) and m['release_ns'] is not None
             and m['sample_ns'] is not None and m['sample_ns'] <= m['release_ns'] <= m['time_ns']
             and 0 <= age <= q['max_age_ns'] and m['provenance'] == 'CERTIFIED_INTERVAL_END')
    duplicated = any(e['source_measurement_record_id'] == m['measurement_record_id']
                     for e in (q.get('response_history') or []))
    pair = q.get('progress_pair')
    epoch = q.get('epoch')
    deferred = q.get('deferred_demand')
    active = bool(epoch and epoch['completion_reason'] is None) or bool(deferred and deferred['deferred_demand_active'])
    direction = q.get('direction')
    obligation = q.get('directional_obligation')
    if obligation is not None:
        direction = obligation['direction']
    expected = 0.0
    movement = 0.0
    if active and pair and direction is not None and q['oldest_unresolved_demand_ns'] is not None:
        start = q['oldest_unresolved_demand_ns']
        if obligation:
            start = max(start, obligation['established_ns'])
        if q.get('startup_outage_direction'):
            start = max(start, q['startup_outage_direction']['established_ns'])
        if pair['update_reason'] == 'QUALIFIED_DIRECTIONAL_PROGRESS':
            start = max(start, pair['progress_pair_ns'] - q['delay_ns'])
        active_s = max(0.0, (m['time_ns'] - start - q['delay_ns']) / 1e9)
        cmd = pre['old_command']['value']
        demand = max(0.0, direction * (cmd - pair['progress_command_reference'])
                     + max(0.0, direction * (pair['progress_command_reference'] - pair['progress_measurement_reference'])))
        expected = min(q['ramp'] * active_s, demand * (1 - math.exp(-active_s / q['tau_s'])))
        if valid:
            movement = direction * (m['measured_speed'] - pair['progress_measurement_reference'])
    ratio = movement / expected if expected > 0 else None
    progress = (valid and not duplicated and active and movement >= q['minimum_motion']
                and ratio is not None and ratio >= q['suspect_ratio'])
    deficient = (valid and not duplicated and active and expected >= q['confirm_expected']
                 and (ratio is None or ratio < q['confirm_ratio'])
                 and m['measurement_record_id'] != q.get('last_measurement_id'))
    return {'valid': valid, 'duplicate': duplicated, 'active': active,
            'expected': expected, 'movement': movement, 'progress': progress, 'deficient': deficient}


def compare(reference_frame, split_frame, *, previous_pre_ids=(), artifacts=(), trusted_context=None):
    if type(trusted_context) is not TrustedContext or not trusted_context.valid():
        return {'mode': MODE, 'status': 'QUALIFICATION_INPUT_MISSING',
                'findings': [{'rule': 'INTEGRITY', 'pointer': '$/trusted-channel-provenance'}], 'rules': list(RULES)}
    independent = trusted_context.data()
    findings = []
    for item in artifacts:
        p = ROOT / item['path']
        if not p.is_file() or sha(p.read_bytes()) != item['raw_sha256']:
            return {'mode': MODE, 'status': 'EVIDENCE_INTEGRITY_INVALID',
                    'findings': [{'rule': 'INTEGRITY', 'pointer': item['path']}], 'rules': list(RULES)}

    def require(condition, rule, pointer):
        if not condition:
            findings.append({'rule': rule, 'pointer': pointer})

    mapping = {'state': 'CMP-A01', 'records': 'CMP-A01', 'transitions': 'CMP-A02',
        'watch_number': 'CMP-A03', 'oldest_unresolved_demand_ns': 'CMP-A03', 'epoch': 'CMP-A03',
        'carried_suspicion_evidence': 'CMP-A04', 'confirmed_latched': 'CMP-A04', 'credited_motion': 'CMP-A04',
        'resolved_pair': 'CMP-A05', 'progress_pair': 'CMP-A05',
        'consumed_samples': 'CMP-A06', 'response_history': 'CMP-A06',
        'startup_demand_suspended': 'CMP-A07', 'startup_observation': 'CMP-A07'}
    try:
        actual = split_frame['after']
        require(set(actual) == set(FIELDS), 'CMP-A08', '$/after:registered-presence')
        for name in FIELDS:
            if name not in actual:
                continue
            diff = first_difference(reference_frame['after'][name], actual[name], '$/after/' + name)
            require(diff is None, mapping.get(name, 'CMP-A08'), diff or name)
        require(first_difference(reference_frame['before'], split_frame['before']) is None,
                'CMP-A08', '$/before')
        pre, safety, plc, post = [split_frame[k] for k in ('PRE', 'SAFETY', 'PLC', 'POST')]
        expected_pre=reference_frame['derived_pre']
        require(pre['old_command']==expected_pre['old_command'],'CMP-B01','$/PRE/independent-old-command')
        for key in ('state','carried_suspicion_evidence','confirmed_latched','credited_motion',
                    'response_history','consumed_samples','episode_progress'):
            require(first_difference(expected_pre['core'][key],split_frame['pre_core'][key]) is None,
                    'CMP-B01','$/PRE/independent-predicate/'+key)
        trusted = decode(reference_frame['after']['previous_observation'])
        require(trusted == independent['source_row'], 'CMP-B04', '$/SAFETY/trusted-source-row')
        source_fields = ('time_ns', 'measured_speed', 'sample_ns', 'release_ns', 'quality', 'measurement_record_id')
        require(all(encode(pre['measurement'][key]) == encode(trusted[key]) for key in source_fields)
                and pre['source_id'] == trusted['measurement_record_id']
                and pre['measurement']['provenance'] == reference_frame['input_provenance'],
                'CMP-B01', '$/PRE/independent-source-binding')
        model = _old_qualification(reference_frame['before'], pre)
        entry = _native(reference_frame['before'])
        evaluation = expected_pre['evaluation']
        if evaluation is not None and evaluation['recovery_reevaluated']:
            # Recovery may activate the already-issued deferred direction and
            # matched pair before qualification. Use trusted old-context math,
            # not the SUT's final claims or a nonexistent entry-state epoch.
            expected_motion = evaluation['expected_motion'] or 0.0
            movement = evaluation['checkpoint_measured_displacement'] or 0.0
            ratio = movement / expected_motion if expected_motion > 0 else None
            model.update(active=True, expected=expected_motion, movement=movement,
                progress=evaluation['qualified_progress'],
                deficient=(model['valid'] and not model['duplicate']
                    and expected_motion >= entry['confirm_expected']
                    and (ratio is None or ratio < entry['confirm_ratio'])
                    and pre['source_id'] != entry['last_measurement_id']))
        old_epoch = entry.get('epoch')
        expected_epoch_id = old_epoch['tracking_epoch_id'] if old_epoch and old_epoch['completion_reason'] is None else None
        require(pre['old_epoch_id'] == expected_epoch_id
                and pre['state'] == decode(split_frame['pre_core']['state']),
                'CMP-B01', '$/PRE/obligation-and-state-binding')
        prior = entry.get('previous_observation')
        expected_old_value = entry['last_command'] if entry['last_command'] is not None else trusted['plc_command']
        expected_old_issue = prior['command_timestamp_ns'] if prior else trusted['command_timestamp_ns']
        require(encode(pre['old_command']['value']) == encode(expected_old_value)
                and pre['old_command']['issue_ns'] == expected_old_issue
                and pre['old_command']['identity'] == 'released-command:' + str(expected_old_issue),
                'CMP-B01', '$/PRE/prior-authorized-command-binding')
        qualified = _native(split_frame['pre_core'])
        delta = qualified['carried_suspicion_evidence'] - entry['carried_suspicion_evidence']
        require(delta <= 0 or model['deficient'], 'CMP-B01', '$/PRE/deficient-source')
        require(delta <= 1, 'CMP-B01', '$/PRE/evidence-count')
        if delta < 0:
            require(model['progress'], 'CMP-B01', '$/PRE/evidence-resolution')
        if pre['state'] == 'TRACKING_FAULT_SUSPECTED':
            require(model['valid'] and model['active'] and model['expected'] >= entry['suspect_expected']
                    and not model['progress'], 'CMP-B01', '$/PRE/suspected-qualification')
        if pre['state'] == 'TRACKING_PROGRESS':
            require(model['progress'], 'CMP-B01', '$/PRE/progress-qualification')
        if not entry['confirmed_latched'] and qualified['confirmed_latched']:
            require(model['deficient'] and qualified['carried_suspicion_evidence'] >= entry['confirm_samples'],
                    'CMP-B01', '$/PRE/confirmation-qualification')
        if not model['valid'] or model['duplicate']:
            require(delta == 0 and qualified['credited_motion'] == entry['credited_motion'],
                    'CMP-B01', '$/PRE/invalid-duplicate-credit')
        spec_map = read('phase5_r5_2_1r4_7_c2_r1_timing_policy_registration.json')['safety_mapping'][pre['state']]
        expected_map = {k: spec_map[k] for k in ('severity', 'reason_codes', 'restriction')}
        require(pre['contribution'] == expected_map, 'CMP-B02', '$/PRE/contribution')
        require(pre['record_id'] not in previous_pre_ids and safety['pre_record_id'] == pre['record_id'],
                'CMP-B03', '$/SAFETY/current-PRE-binding')
        require(safety['independent_channels'] == independent['independent_channels'],
                'CMP-B04', '$/SAFETY/independent-channel-input')
        require(safety['retained_fault_reasons'] == independent['retained_fault_reasons'],
                'CMP-B04', '$/SAFETY/independent-retained-history')
        expected_policy = policy_expected(pre['state'], independent['independent_channels'],
                                          independent['retained_fault_reasons'])
        expected_reasons = set(expected_policy['reason_codes'])
        require(len(safety['reason_codes']) == len(set(safety['reason_codes']))
                and set(safety['reason_codes']) == expected_reasons, 'CMP-B04', '$/SAFETY/all-reasons')
        require(safety['severity'] == expected_policy['severity'], 'CMP-B04', '$/SAFETY/severity')
        require(sha(canonical(pre)) == split_frame['immutable_pre_digest']
                and safety['pre_digest'] == split_frame['immutable_pre_digest']
                and plc['safety_digest'] == split_frame['immutable_safety_digest']
                and sha(canonical(safety)) == split_frame['immutable_safety_digest'],
                'CMP-B05', '$/committed-bytes')
        require(split_frame['commits'] == ['PRE_EVIDENCE_COMMIT', 'SAFETY_DECISION_COMMIT',
            'PLC_COMMAND_ISSUE', 'POST_FINAL_PUBLICATION_COMMIT'] and plc['producer'] == 'SIMULATED_PLC',
            'CMP-C01', '$/authority-order')
        producers = [e for e in split_frame['access_log'] if e['kind'] == 'VERIFIED_OUTPUT_TOKEN']
        require(len(producers) == 1 and producers[0]['actor'] == 'SIMULATED_PLC'
                and producers[0]['record_id'] == plc['record_id'], 'CMP-C01', '$/actual-producer-receipt')
        require([r['phase'] for r in (pre, safety, plc, post)] == ['PRE', 'SAFETY', 'PLC', 'POST']
                and all(type(r['time_ns']) is int and r['time_ns'] == trusted['time_ns'] for r in (pre, safety, plc, post)),
                'CMP-C01', '$/phase-time-cuts')
        require(plc['numeric_hardware_authorization'] == 'OUT_OF_SCOPE'
                and plc['scope'] == 'SIMULATED_PLC_CAUSAL_OWNERSHIP'
                and plc['value_scope'] == 'FIXTURE_EXOGENOUS_COMMAND_VALUE',
                'CMP-C01', '$/PLC/scope')
        require(not any(e['actor'] == 'PRE' and (e['kind'] == 'DENIED_FUTURE_COMMAND_ACCESS'
            or e.get('name') in ('plc_command', 'future_command', 'schedule')) for e in split_frame['access_log']),
            'CMP-C02', '$/PRE/access-capability')
        tx = pre['transaction_id']
        require(all(r['record_id'] == tx + ':' + phase for r, phase in zip((pre, safety, plc, post), ('PRE', 'SAFETY', 'PLC', 'POST')))
                and pre['evidence_commit_id'] == tx + ':E' and plc['plc_cycle_id'] == tx + ':PLC',
                'CMP-C03', '$/deterministic-record-identities')
        require(all(r['transaction_id'] == tx for r in (safety, plc, post))
                and plc['safety_id'] == safety['record_id'] and post['pre_id'] == pre['record_id']
                and post['plc_id'] == plc['record_id'], 'CMP-C03', '$/transaction-links')
        changed = (plc['command'], plc['issue_ns']) != (pre['old_command']['value'], pre['old_command']['issue_ns'])
        require(type(post['enrolled_new_command']) is bool and post['enrolled_new_command'] == changed,
                'CMP-C03', '$/POST/enrollment-once')
        require(encode(plc['command']) == encode(trusted['plc_command'])
                and plc['issue_ns'] == trusted['command_timestamp_ns']
                and plc['command_id'] == 'released-command:' + str(trusted['command_timestamp_ns']),
                'CMP-C03', '$/PLC/frozen-output-binding')
        require(split_frame.get('publication_count', 1) == 1, 'CMP-C03', '$/POST/publication-count')
        require(post['state'] == decode(actual['state'])
                and encode(post['confirmed_latched']) == actual['confirmed_latched'],
                'CMP-C03', '$/POST/final-core-binding')
        authoritative = split_frame['authoritative_after']
        require(_evidence_vector(split_frame['pre_core']) == _evidence_vector(authoritative),
                'CMP-C04', '$/POST/context-only')
        require(sha(canonical(split_frame['pre_core'])) == pre['core_digest'],
                'CMP-B05', '$/PRE/committed-core-bytes')
        require(all(actual[k] == authoritative[k] for k in FIELDS if k != 'response_history'),
                'CMP-C04', '$/POST/projection-history-only')
        # Independent reconstruction: never calls SUT projection code or reads
        # expected final legacy output to decide whether to transform.
        history = decode(authoritative['response_history'])
        previous = decode(reference_frame['before']['response_history'])
        start = len(previous)
        expected_view = previous + json.loads(canonical(history[start:]))
        expected_links = []
        if plc['command'] == pre['old_command']['value'] and plc['issue_ns'] != pre['old_command']['issue_ns']:
            require(plc['issue_ns'] == pre['time_ns'], 'CMP-C03', '$/projection/actual-issue-time')
            for index in range(start, len(history)):
                entry = history[index]
                require(entry['source_measurement_record_id'] == pre['source_id']
                    and entry['evaluation_tick_ns'] == pre['time_ns']
                    and entry['command_timestamp_ns'] == pre['old_command']['issue_ns'],
                    'CMP-C03', '$/projection/causal-attribution')
                projected = {**entry, 'command_timestamp_ns': plc['issue_ns']}
                expected_view[index] = projected
                expected_links.append({'policy': 'M1-SEM01-POST-LEGACY-HISTORY-v1', 'entry_index': index,
                    'transaction_id': tx, 'pre_id': pre['record_id'],
                    'pre_digest': sha(canonical(pre)), 'pre_core_digest': pre['core_digest'],
                    'plc_id': plc['record_id'], 'plc_digest': sha(canonical(plc)),
                    'source_id': pre['source_id'], 'watch_id': entry['logical_episode_id'],
                    'obligation_id': entry['directional_obligation_id'],
                    'old_command_id': pre['old_command']['identity'], 'new_command_id': plc['command_id'],
                    'old_issue_ns': pre['old_command']['issue_ns'], 'new_issue_ns': plc['issue_ns'],
                    'authoritative_entry_digest': sha(canonical(entry)),
                    'projected_entry_digest': sha(canonical(projected))})
        require(actual['response_history'] == encode(expected_view), 'CMP-C03', '$/projection/exact-view')
        require(split_frame['legacy_projection_bindings'] == expected_links,
                'CMP-C03', '$/projection/immutable-causal-bindings')
        require(split_frame['status'] == 'COMPLETE' and split_frame['command_issue_status'] == 'ISSUED'
                and not split_frame.get('unknown_coerced_to_issued', False),
                'CMP-C05', '$/transaction-completeness')
        before_public = len(decode(reference_frame['after']['transitions']))
        require(len(decode(actual['transitions'])) == before_public, 'CMP-A02', '$/public-event-count')
    except (KeyError, TypeError, ValueError, OverflowError) as ex:
        return {'mode': MODE, 'status': 'EVIDENCE_INTEGRITY_INVALID',
                'findings': findings + [{'rule': 'INTEGRITY', 'pointer': str(ex)}], 'rules': list(RULES)}
    return {'mode': MODE, 'status': 'BEHAVIORAL_DIFFERENCE' if findings else 'PASS',
            'findings': findings, 'rules': list(RULES)}


def compare_traces(reference_frames, split_frames, *, oracle=None):
    if len(reference_frames) != len(split_frames):
        return {'mode': MODE, 'status': 'BEHAVIORAL_DIFFERENCE',
                'findings': [{'rule': 'CMP-C03', 'pointer': '$/trace:publication-count'}]}
    previous = []
    for index, (reference, split) in enumerate(zip(reference_frames, split_frames)):
        context = oracle.context(index, reference_frames) if oracle is not None else None
        result = compare(reference, split, previous_pre_ids=previous, trusted_context=context)
        if result['status'] != 'PASS':
            return {**result, 'first_divergent_row': index, 'time_ns': split.get('PRE', {}).get('time_ns')}
        previous.append(split['PRE']['record_id'])
    return {'mode': MODE, 'status': 'PASS', 'findings': [], 'compared_rows': len(split_frames), 'rules': list(RULES)}


def incomplete_assertions(audit):
    """Policy-only in-memory checks, never durability qualification."""
    allowed = ['PRE_EVIDENCE_COMMIT', 'SAFETY_DECISION_COMMIT', 'PLC_COMMAND_ISSUE']
    journal = audit.get('command_record')
    last = audit.get('last_publication')
    known = audit['command_issue_status'] != 'ISSUED' or (
        journal is not None and journal['producer'] == 'SIMULATED_PLC'
        and journal['transaction_id'] == audit['transaction_id'] and 'PLC_COMMAND_ISSUE' in audit['commits'])
    historical = last is None or (last['transaction_id'] != audit['transaction_id'] and last['time_ns'] < audit['time_ns'])
    passed = (audit['status'] == 'INCOMPLETE' and audit['integrity'] == 'INVALID_CONTINUATION'
              and audit['command_issue_status'] in ('UNKNOWN', 'ISSUED', 'NOT_ISSUED')
              and audit['commits'] == allowed[:len(audit['commits'])] and 1 <= len(audit['commits']) <= 3
              and known and historical and not audit.get('automatic_resend', False)
              and not audit.get('fresh_publication', False))
    return {'mode': MODE, 'durability_qualified': False, 'passed': passed, 'rule': 'CMP-C05'}


def prefix_inventory_from_persisted_reference(path, expected_raw_sha256):
    """Prepared for future approved runs. No split-dependent selector."""
    raw = (ROOT / path).read_bytes()
    if sha(raw) != expected_raw_sha256:
        raise ValueError('REFERENCE_PERSISTENCE_MISMATCH')
    data = json.loads(raw)
    if data['origin'] != 'FROZEN_REFERENCE':
        raise ValueError('SPLIT_OUTPUT_SELECTOR_FORBIDDEN')
    from v0_2.tests.data.tracking_qualification.r46_prefix import select
    return select(data['observations'], data['records'])


def normalize_new_metadata(record, execution_id):
    """Only named new P1 identities; never source/old IDs/timestamps/core values."""
    output = json.loads(canonical(record))
    keys = {'transaction_id', 'record_id', 'pre_record_id', 'pre_id', 'plc_id',
            'safety_id', 'evidence_commit_id', 'plc_cycle_id'}
    for name in ('PRE', 'SAFETY', 'PLC', 'POST'):
        for key in keys:
            value = output.get(name, {}).get(key)
            if isinstance(value, str) and value.startswith(execution_id + ':'):
                output[name][key] = '<RUN>:' + value[len(execution_id) + 1:]
    for event in output.get('access_log', []):
        if event['actor'] == 'SIMULATED_PLC' and event['kind'] == 'VERIFIED_OUTPUT_TOKEN':
            value = event['record_id']
            if value.startswith(execution_id + ':'):
                event['record_id'] = '<RUN>:' + value[len(execution_id) + 1:]
    return output


def repeat_fingerprint(reference, record, execution_id, *, trusted_context=None):
    if compare(reference, record, trusted_context=trusted_context)['status'] != 'PASS':
        raise ValueError('INVALID_REPEAT_GRAPH')
    output = normalize_new_metadata(record, execution_id)
    # These are new P1 digest bindings, not reference/source identities.
    # Original committed bytes were validated above and remain in raw evidence.
    output['immutable_pre_digest'] = sha(canonical(output['PRE']))
    output['SAFETY']['pre_digest'] = output['immutable_pre_digest']
    output['immutable_safety_digest'] = sha(canonical(output['SAFETY']))
    output['PLC']['safety_digest'] = output['immutable_safety_digest']
    return sha(canonical(output))



